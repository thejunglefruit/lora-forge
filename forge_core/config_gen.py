"""Backend config generation from the registry presets.

Current backend: YAML for ai-toolkit. The structure follows ai-toolkit's public FLUX
LoRA example; the EXACT keys must be checked against the version installed on the GPU
box (the YAML header says so). The config is generated from scratch from the registry,
not copied.
"""
from __future__ import annotations

import hashlib
from dataclasses import dataclass
from pathlib import Path
from typing import Any

import yaml

from .registry import ModelSpec


def scale_steps(preset: dict[str, Any], n_images: int) -> int:
    """Scales steps to the dataset size, within the preset's floor and ceiling."""
    per_img = int(preset.get("steps_per_image", 100))
    base = int(preset.get("base_steps", 2000))
    lo = int(preset.get("steps_min", 1000))
    hi = int(preset.get("steps_max", 4000))
    proposed = max(base, per_img * max(n_images, 1))
    return max(lo, min(hi, proposed))


@dataclass
class GeneratedConfig:
    run_id: str
    steps: int
    data: dict[str, Any]
    yaml_text: str

    @property
    def config_hash(self) -> str:
        return hashlib.sha256(self.yaml_text.encode("utf-8")).hexdigest()[:12]


def build_aitoolkit_config(
    *,
    run_id: str,
    model: ModelSpec,
    lora_type: str,
    trigger: str | None,
    dataset_folder: str,
    output_folder: str,
    n_images: int,
    eval_prompts: list[str],
) -> GeneratedConfig:
    if model.backend != "ai-toolkit":
        raise ValueError(f"build_aitoolkit_config does not support backend '{model.backend}'.")

    p = model.preset
    steps = scale_steps(p, n_images)
    save_every = max(200, steps // 4)

    is_flux = model.arch in ("flux", "flux2")

    data: dict[str, Any] = {
        "job": "extension",
        "config": {
            "name": run_id,
            "process": [
                {
                    "type": "sd_trainer",
                    "training_folder": output_folder,
                    "device": "cuda:0",
                    "trigger_word": trigger or "",
                    "network": {
                        "type": "lora",
                        "linear": p["rank"],
                        "linear_alpha": p["alpha"],
                    },
                    "save": {
                        "dtype": "float16",
                        "save_every": save_every,
                        "max_step_saves_to_keep": 4,
                    },
                    "datasets": [
                        {
                            "folder_path": dataset_folder,
                            "caption_ext": "txt",
                            "caption_dropout_rate": 0.05,
                            "shuffle_tokens": False,
                            "cache_latents_to_disk": True,
                            "resolution": p["resolutions"],
                        }
                    ],
                    "train": {
                        "batch_size": 1,
                        "steps": steps,
                        "gradient_accumulation_steps": 1,
                        "train_unet": True,
                        "train_text_encoder": False,
                        "gradient_checkpointing": True,
                        "noise_scheduler": p["noise_scheduler"],
                        "optimizer": p["optimizer"],
                        "lr": p["lr"],
                        "dtype": p["dtype"],
                    },
                    "model": {
                        "name_or_path": model.name_or_path,
                        "is_flux": is_flux,
                        "quantize": p.get("quantize", False),
                    },
                    "sample": {
                        "sampler": p["sampler"],
                        "sample_every": save_every,
                        "width": p["resolutions"][0],
                        "height": p["resolutions"][0],
                        "prompts": eval_prompts,
                        "neg": "",
                        "seed": 42,
                        "walk_seed": True,
                        "guidance_scale": p["guidance_scale"],
                        "sample_steps": p["sample_steps"],
                    },
                }
            ],
        },
        "meta": {"name": run_id, "version": "1.0"},
    }

    header = (
        "# Generated by LoRA Forge. VERIFY the keys against the ai-toolkit version\n"
        f"# installed on the GPU box. model={model.model_id} arch={model.arch} "
        f"backend={model.backend}\n"
    )
    yaml_text = header + yaml.safe_dump(data, sort_keys=False, allow_unicode=True)
    return GeneratedConfig(run_id=run_id, steps=steps, data=data, yaml_text=yaml_text)


def write_config(cfg: GeneratedConfig, path: Path) -> str:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(cfg.yaml_text, encoding="utf-8")
    return cfg.config_hash
